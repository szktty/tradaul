import 'dart:convert';
import 'dart:io';

import 'package:args/args.dart';
import 'package:result_dart/result_dart.dart';
import 'package:tradaul/src/compiler/debug_print.dart';
import 'package:tradaul/src/runtime/compiled_code.dart';
import 'package:tradaul/src/runtime/lua_context.dart';
import 'package:tradaul/src/utils/file.dart';
import 'package:tradaul/tradaul.dart';

const String appName = 'Tradaul';

Future<void> main(List<String> arguments) async {
  final parser = ArgParser()
    ..addFlag(
      'help',
      abbr: 'h',
      negatable: false,
      help: 'Display this help message',
    )
    ..addFlag(
      'version',
      negatable: false,
      help: 'Display the version of $appName',
    )
    ..addFlag('verbose', negatable: false, help: 'Enable verbose output')
    ..addFlag('debug', negatable: false, help: 'Enable debug mode')
    ..addFlag('syntax', abbr: 'c', negatable: false, help: 'Check syntax only')
    ..addFlag('bytecode', abbr: 'b', negatable: false, help: 'Show generated bytecode and exit')
    ..addOption('execute', abbr: 'e', help: 'Pass string as source code')
    ..addFlag(
      'stdin',
      abbr: 'i',
      negatable: false,
      help: 'Read source code from stdin',
    );

  ArgResults args;
  try {
    args = parser.parse(arguments);
  } on FormatException catch (e) {
    printError(e.message);
    exit(1);
  }

  if (args['help'] == true) {
    printUsage(parser.usage);
    return;
  }

  if (args['version'] == true) {
    stdout.write('$appName ${LuaContext.thisVersion}');
    return;
  }

  final verbose = args['verbose'] as bool;
  final debug = args['debug'] as bool;
  final syntax = args['syntax'] as bool;
  final bytecode = args['bytecode'] as bool;
  final script = args['execute'] as String?;
  final useStdin = args['stdin'] as bool;

  final remaining = args.rest;

  if (remaining.isEmpty && script == null && !useStdin) {
    printUsage(parser.usage);
    return;
  }

  var logLevel = LuaLogLevel.error;
  if (verbose) {
    logLevel = LuaLogLevel.verbose;
  } else if (debug) {
    logLevel = LuaLogLevel.debug;
  }

  final options = LuaContextOptions(
    debug: debug,
    logLevel: logLevel,
    checkSyntaxOnly: syntax,
  );
  final context = await LuaContext.create(name: '<stdin>', options: options);

  if (script != null) {
    if (bytecode) {
      final compileResult = compileForBytecode(context, script, '<string>');
      if (compileResult != null) {
        if (compileResult.isSuccess()) {
          printBytecode(compileResult.getOrThrow());
        } else {
          final error = compileResult.exceptionOrNull()!;
          printError(error.toString());
          exit(1);
        }
      }
    } else {
      final result = await context.execute(script, path: '<stdin>');
      checkResult(result);
    }
  }

  if (useStdin) {
    final stdinSource = await readFromStdin();
    if (bytecode) {
      final compileResult = compileForBytecode(context, stdinSource, '<stdin>');
      if (compileResult != null) {
        if (compileResult.isSuccess()) {
          printBytecode(compileResult.getOrThrow());
        } else {
          final error = compileResult.exceptionOrNull()!;
          printError(error.toString());
          exit(1);
        }
      }
    } else {
      final result = await context.execute(stdinSource, path: '<stdin>');
      checkResult(result);
    }
  }

  if (remaining.isNotEmpty) {
    final path = remaining.first;
    final allArgs = [Platform.script.toFilePath(), ...arguments];
    final base = allArgs.indexOf(path);
    final before = allArgs.sublist(0, base);
    final after = allArgs.sublist(base);

    final loadResult = FileUtils.read(path);
    String? source;
    try {
      source = loadResult.getOrThrow();
    } on String catch (e) {
      printError(e);
      exit(1);
    } on Exception catch (e) {
      printError('$e');
      exit(1);
    }
    
    if (bytecode) {
      final compileResult = compileForBytecode(context, source, path);
      if (compileResult != null) {
        if (compileResult.isSuccess()) {
          printBytecode(compileResult.getOrThrow());
        } else {
          final error = compileResult.exceptionOrNull()!;
          printError(error.toString());
          exit(1);
        }
      }
    } else {
      final result = await context.execute(
        source,
        path: path,
        arguments: (before, after),
      );
      checkResult(result);
    }
  }
}

void printUsage(String usage) {
  stdout
    ..writeln('Usage: $appName [OPTIONS] [SCRIPT [ARGS]]')
    ..writeln(usage);
}

void printError(String message) {
  stdout.writeln('Error: $message');
}

Future<String> readFromStdin() async {
  final lines = <String>[];
  await for (final line in stdin
      .transform(utf8.decoder)
      .transform(const LineSplitter())) {
    lines.add(line);
  }
  return lines.join('\n');
}

Result<LuaCompiledCode>? compileForBytecode(LuaContext context, String source, String path) {
  return context.compile(source, path: path);
}

void printBytecode(LuaCompiledCode code) {
  DebugPrint.compiledFunction(
    code: code.chunk,
    name: code.chunk.name ?? '<main>',
    firstLine: code.chunk.firstLine,
    lastLine: code.chunk.lastLine,
    arity: code.chunk.arity,
    variadic: code.chunk.variadic,
    method: code.chunk.method,
    opcodes: code.chunk.opcodes,
    constants: code.chunk.constants,
    locals: [], // この情報は利用可能ではありません
    innerLocals: code.chunk.locals,
    upvalues: code.chunk.upvalues,
    protos: code.chunk.prototypes,
    lineInfo: code.chunk.lineInfo,
    comments: const {}, // この情報は利用可能ではありません
  );
}

void checkResult(LuaExecutionResult result) {
  final context = result.exceptionOrNull();
  if (context != null) {
    printError(context.toString());
    exit(1);
  }
}
